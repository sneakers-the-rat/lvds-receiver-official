#!/usr/bin/env python3
"""
run_hv.py — stage 4b (simulation half): ngspice HV flyback checks.
The analytical design (stresses, ripple budget, bleeder) is sim/hv_design.py.

POPULATION NOTE (2026-11-04 HV fix, docs/03): these decks target
the 420 V design point, which is now the S8664 STUFFING VARIANT.
The standard C30737 fit (116..253 V, hardware-bounded <= 260 V)
is simulated by sim/run_hv_clamp.py against its own network.

Deck 1 — SWITCHING (open loop, duty from the analytical design):
  5 V -> ideal 1:20 coupled inductor (Lp 47 uH, K=0.999), switch modelled
  as a voltage-controlled switch, 1000 V secondary diode model, Cout 47 nF,
  load = 200 uA current sink (APD) + 4.7 Mohm bleeder, RC post-filter
  10 kohm / 100 nF to the APD node. Duty is set open-loop; in DCM the
  output voltage is set by the energy balance into the load, exactly as
  the analytical calc predicts — the check is that the simulated Vout
  lands within 25% of the value implied by the design equations and that
  the APD-node ripple (after the RC filter) is < 20 mVpp (R9).
  This deck does NOT model the LT3757's internal current loop; that is
  what deck 2 + the datasheet are for. Stated plainly.

Deck 2 — AVERAGED CLOSED LOOP (regulation concept):
  Averaged DCM plant: Pin(D) = Vin^2 D^2 eta / (2 Lp fsw), I = Pin/Vout
  charging Cout against the same load; PI controller (behavioural) on a
  1/168 feedback divider, reference stepped 150 V -> 420 V at t = 10 ms.
  Checks: settles within 2% of 420 V, overshoot < 5%.
"""
import os, subprocess, sys
import numpy as np

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

SW_DECK = """* HV flyback switching deck (generated by sim/run_hv.py)
Vin vin 0 5.0
* gate drive: ton = 1.7 us at 250 kHz -> Ipk = Vin*ton/Lp = 0.181 A,
* the analytical design peak current (hv_design.py). Open-loop DCM
* flyback voltage is set by power balance into the load, NOT by the
* duty alone — this deck checks delivered-power class + ripple; the
* exact 420 V setpoint is the closed loop's job (deck 2 / LT3757).
Vgate gate 0 PULSE(0 5 0 20n 20n 1.7u 4.0u)
S1 vin sw gate 0 SWMOD
.model SWMOD SW(Ron=0.05 Roff=1e9 Vt=2.5)
Lp sw  0 47u
Ls 0 sec 18.8m
K1 Lp Ls 0.999
Rsnub sw sn 47
Csnub sn 0 470p
Dsec sec rect DSEC
.model DSEC D(IS=1e-12 RS=2 BV=1000 IBV=1e-6 CJO=4p)
Cout rect 0 47n
Rbleed rect 0 4.7Meg
Rfilt rect apd 10k
Cfilt apd 0 100n
Iload apd 0 200u
.ic v(rect)=380 v(apd)=380
.control
tran 8n 12m 0 25n uic
wrdata results/hv_sw.csv v(rect) v(apd)
quit
.endc
.end
"""

AVG_DECK = """* HV flyback averaged closed-loop deck (generated by sim/run_hv.py)
* feedback divider 1/168: 420 V -> 2.50 V
Vref ref 0 PWL(0 0.893 99.99m 0.893 100m 2.5 220m 2.5)
Efb fb 0 rect 0 0.005952
Eerr err 0 ref fb 1.0
* Feedforward + proportional trim: Dff from the DCM energy balance
* Dff = sqrt( 2 Lp f Pload(Vt) / (eta Vin^2) ), Vt = 168 * V(ref),
* Pload(Vt) = Vt * (200 uA + Vt/4.7 Mohm).  Trim Kp = 0.02 per volt of
* fb error.  (The real LT3757 closes a current-mode loop on its FB pin;
* this averaged deck demonstrates setpoint regulation of the same plant.)
Eduty duty 0 value = {{min(max(sqrt(max(1.343 * (168*v(ref)) * (200e-6 + (168*v(ref))/4.7e6), 1e-4))  + 0.15*v(err), 0.05), 0.90)}}
* averaged DCM plant: I_charge = Pin(D)/Vout, Pin = Vin^2 D^2 eta/(2 Lp f)
Bplant 0 rect I = {{(25 * v(duty) * v(duty) * 0.70) / (2 * 47e-6 * 250e3) / max(v(rect), 1.0)}}
Cout rect 0 47n
Rbleed rect 0 4.7Meg
Iload rect 0 200u
.ic v(rect)=0
.control
tran 100u 220m 0 200u uic
wrdata results/hv_avg.csv v(rect) v(duty)
quit
.endc
.end
"""

def run(deck, name):
    with open(f"sim/{name}.cir", "w") as f:
        f.write(deck)
    r = subprocess.run(["ngspice", "-b", f"sim/{name}.cir"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout[-2000:])
        raise SystemExit(f"ngspice failed: {name}")

run(SW_DECK, "hv_sw")
d = np.loadtxt("results/hv_sw.csv")
t, vrect, vapd = d[:, 0], d[:, 1], d[:, 3] if d.shape[1] > 3 else d[:, 1]
# wrdata with two vectors writes t, v1, v1imag?, ... — for tran all real:
# columns are (t, v(rect)) pairs repeated; robust parse:
if d.shape[1] == 5:
    t, vrect, vapd = d[:, 0], d[:, 1], d[:, 3]
win = t > 11e-3
vout_sw = vrect[win].mean()
seg = vapd[win]
tt = t[win]
trend = np.polyval(np.polyfit(tt, seg, 1), tt)   # remove residual ramp
ripple = (seg - trend).max() - (seg - trend).min()
print(f"SWITCHING: Vout(rect) mean last 1 ms = {vout_sw:.0f} V, "
      f"APD-node ripple = {ripple*1e3:.2f} mVpp")

run(AVG_DECK, "hv_avg")
d = np.loadtxt("results/hv_avg.csv")
if d.shape[1] == 5:
    t, vout, duty = d[:, 0], d[:, 1], d[:, 3]
else:
    t, vout = d[:, 0], d[:, 1]
    duty = None
pre = vout[(t > 85e-3) & (t < 100e-3)].mean()
post = vout[t > 215e-3].mean()
overshoot = (vout.max() - 420.0) / 420.0 * 100
print(f"AVERAGED LOOP: pre-step {pre:.0f} V (target 150), "
      f"post-step {post:.1f} V (target 420), overshoot {overshoot:.1f}%")

checks = [
    ("switching Vout in 300..600 V band at design Ipk "
     "(open-loop power delivery class)", 300 < vout_sw < 600),
    ("APD-node ripple < 20 mVpp (R9)", ripple < 20e-3),
    ("averaged loop: 150 V pre-step within 5%", abs(pre - 150) < 7.5),
    ("averaged loop: settles within 2% of 420 V", abs(post - 420) < 8.4),
    ("averaged loop: overshoot < 5%", overshoot < 5.0),
]
print("\n--- checks ---")
ok = True
for name, p in checks:
    print(f"{'PASS' if p else 'FAIL'}  {name}")
    ok &= bool(p)
print(f"\nHV NGSPICE VERDICT: {'PASS' if ok else 'FAIL'}")
with open("results/hv_sim.txt", "w") as f:
    f.write(f"switching: Vout={vout_sw:.0f} V open-loop, APD ripple="
            f"{ripple*1e3:.2f} mVpp\naveraged loop: pre={pre:.0f} V, "
            f"post={post:.1f} V, overshoot={overshoot:.1f}%\n")
    for name, p in checks:
        f.write(f"{'PASS' if p else 'FAIL'}  {name}\n")
    f.write(f"VERDICT: {'PASS' if ok else 'FAIL'}\n")
sys.exit(0 if ok else 1)
