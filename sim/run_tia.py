#!/usr/bin/env python3
"""
run_tia.py — stage 4a: ngspice TIA verification (OPA657 + C30737 APD model).

Runs three ngspice batch simulations (decks generated here so the exact
stimulus is in version control):
  AC   : current injection at the TIA input -> |Zt(f)| -> f-3dB, peaking
  TRAN : current step (0 -> 36 uA, the I1-I0 swing at -34 dBm/740 nm/M=50)
         and a 50 Mbps alternating pulse train -> settling within 1 UI
  NOISE: .noise referred to output, integrated 10 kHz..3 GHz, compared with
         the python link budget (0.569 mV rms) within 3 dB

PASS criteria (printed):
  f-3dB >= 50 MHz (R1); peaking < 3 dB; step settles to within 5% of final
  in < 20 ns (1 UI); integrated output noise within 3 dB of link budget.
"""
import math, os, subprocess, sys
import numpy as np

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

CIR_HEAD = """* TIA verification deck (generated by sim/run_tia.py)
.include sim/opa657_macromodel.lib
Vcc vcc 0 5.0
Vbias vbias 0 1.0
* APD: current source, Cd=1pF to AC ground (cathode HV is AC-grounded
* through its filter cap), dark resistance 100 Meg
Iph 0 inn {stim}
Cd  inn 0 1.0p
Rd  inn 0 100Meg
* TIA: OPA657, IN+ at 1.0 V bias, Rf=3.3k, Cf=0.45p total
XU1 vbias inn vcc 0 out OPA657
Rf  out inn 3.3k
Cf  out inn 0.45p
.end
"""

def run_ngspice(deck, name):
    path = f"sim/{name}.cir"
    with open(path, "w") as f:
        f.write(deck)
    r = subprocess.run(["ngspice", "-b", path], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout[-3000:], r.stderr[-2000:])
        raise SystemExit(f"ngspice failed on {name}")
    return r.stdout

def ngb(path, fatal=True):
    """Run an ngspice deck file LOUDLY. The inline subprocess calls
    this replaces used check=True + capture_output=True, which raised
    CalledProcessError with the captured output never printed — in CI
    that swallowed the actual ngspice error entirely (GH Actions run
    41714928437: tia_ac.cir exited 1 under Ubuntu ngspice 36 with no
    diagnosable message in the log). On failure this prints the full
    captured stdout+stderr tails to stderr before raising."""
    r = subprocess.run(["ngspice", "-b", path], capture_output=True, text=True)
    if r.returncode != 0:
        print(f"--- ngspice FAILED on {path} (exit {r.returncode}) ---",
              file=sys.stderr)
        print("--- ngspice stdout (tail) ---", file=sys.stderr)
        print(r.stdout[-4000:], file=sys.stderr)
        print("--- ngspice stderr (tail) ---", file=sys.stderr)
        print(r.stderr[-4000:], file=sys.stderr)
        if fatal:
            raise SystemExit(f"ngspice failed on {path} "
                             f"(exit {r.returncode}) — output above")
    return r

def read_wrdata(path):
    d = np.loadtxt(path)
    return d[:, 0], d[:, 1::2] + 1j * d[:, 2::2] if d.shape[1] > 2 else (d[:, 0], d[:, 1])

results = {}

# ---------- AC ----------
deck = CIR_HEAD.format(stim="ac 1") + """
.control
ac dec 200 1e5 3e9
wrdata results/tia_ac.csv db(v(out)) ph(v(out))
.endc
"""
# wrdata with db() writes a single real column pair; handle generically:
run_ngspice(deck.replace(".end\n", ""), "tia_ac") if False else None
with open("sim/tia_ac.cir", "w") as f:
    f.write(CIR_HEAD.format(stim="ac 1").replace(".end\n", "") + """
.control
ac dec 200 1e5 3e9
wrdata results/tia_ac.csv db(v(out))
.endc
.end
""")
ngb("sim/tia_ac.cir")
d = np.loadtxt("results/tia_ac.csv")
freq, gdb = d[:, 0], d[:, 1]
g0 = gdb[0]
below = np.where(gdb <= g0 - 3.0)[0]
f3db = freq[below[0]] if len(below) else float("nan")
peaking = gdb.max() - g0
results["f3db_MHz"] = f3db / 1e6
results["peaking_dB"] = peaking
print(f"AC: |Zt(0)| = {10**(g0/20):.0f} ohm, f-3dB = {f3db/1e6:.1f} MHz, "
      f"peaking = {peaking:.2f} dB")

# ---------- TRAN ----------
with open("sim/tia_tran.cir", "w") as f:
    f.write(CIR_HEAD.format(
        stim="PULSE(0 36u 10n 0.5n 0.5n 60n 200n)").replace(".end\n", "") + """
.control
tran 0.05n 160n
wrdata results/tia_step.csv v(out)
.endc
.end
""")
ngb("sim/tia_tran.cir")
d = np.loadtxt("results/tia_step.csv")
t, v = d[:, 0], d[:, 1]
vfinal = v[(t > 40e-9) & (t < 65e-9)].mean()  # plateau of the 60 ns pulse
vbase = v[t < 8e-9].mean()
# settling: first time after the step edge (10.5 ns) from which the output
# stays within 5% of (vfinal-vbase) for the rest of the step window
target = vbase + 0.95 * (vfinal - vbase)
ok_idx = np.where((t > 10.5e-9) & (t < 68e-9))[0]
settle_t = float("nan")
for i in ok_idx:
    if np.all(np.abs(v[i:ok_idx[-1]] - vfinal) <= 0.05 * abs(vfinal - vbase)):
        settle_t = t[i] - 10.5e-9
        break
results["settle_ns"] = settle_t * 1e9
results["step_mV"] = (vfinal - vbase) * 1e3
print(f"TRAN step: swing = {(vfinal-vbase)*1e3:.1f} mV, settles to 5% in "
      f"{settle_t*1e9:.1f} ns")

with open("sim/tia_pulse.cir", "w") as f:
    f.write(CIR_HEAD.format(
        stim="PULSE(0 36u 5n 0.5n 0.5n 9n 20n)").replace(".end\n", "") + """
.control
tran 0.05n 400n
wrdata results/tia_pulse.csv v(out)
.endc
.end
""")
ngb("sim/tia_pulse.cir")
d = np.loadtxt("results/tia_pulse.csv")
t, v = d[:, 0], d[:, 1]
# eye opening at the centre of each UI in the last 10 periods
# pulse train: 9 ns high / 11 ns low per 20 ns UI starting at 5 ns, so
# UI centres alternate between the high phase (~+12 ns offset) and the
# low phase (~+2 ns offset) of each period — sample both phases.
hi, lo = [], []
for c in np.arange(205e-9, 395e-9, 20e-9):
    hi.append(v[np.argmin(np.abs(t - (c + 7e-9)))])
    lo.append(v[np.argmin(np.abs(t - (c + 17e-9)))])
hi, lo = np.array(hi), np.array(lo)
print(f"TRAN 1010 pattern: high-phase samples {hi.mean()*1e3:.1f} "
      f"+/- {hi.std()*1e3:.1f} mV, low-phase {lo.mean()*1e3:.1f} "
      f"+/- {lo.std()*1e3:.1f} mV -> eye "
      f"{abs(hi.mean()-lo.mean())*1e3:.1f} mV (of 118.8 mV step swing)")

# ---------- NOISE ----------
with open("sim/tia_noise.cir", "w") as f:
    f.write(CIR_HEAD.format(stim="dc 0 ac 1").replace(".end\n", "") + """
.control
noise v(out) Iph dec 100 1e4 3e9
setplot noise1
wrdata results/tia_noise.csv onoise_spectrum
.endc
.end
""")
r = ngb("sim/tia_noise.cir", fatal=False)
try:
    d = np.loadtxt("results/tia_noise.csv")
    fn, dens = d[:, 0], np.abs(d[:, 1])
    vrms = math.sqrt(np.trapz(dens**2, fn))
    results["noise_mV"] = vrms * 1e3
    print(f"NOISE: integrated output noise = {vrms*1e3:.3f} mV rms "
          f"(link budget: 0.569 mV rms)")
except Exception as e:
    print("NOISE: could not parse ngspice noise output:", e)
    print(r.stdout[-1500:])
    results["noise_mV"] = float("nan")

checks = [
    ("f-3dB >= 50 MHz (R1)", results["f3db_MHz"] >= 50),
    ("peaking < 3 dB", results["peaking_dB"] < 3.0),
    ("step settles to 5% within 1 UI (20 ns)", results["settle_ns"] < 20),
    ("noise within 3 dB of link budget 0.569 mV",
     abs(20 * math.log10(results["noise_mV"] / 0.569)) < 3.0),
]
print("\n--- checks ---")
ok = True
for name, p in checks:
    print(f"{'PASS' if p else 'FAIL'}  {name}")
    ok &= bool(p)
print(f"\nTIA NGSPICE VERDICT: {'PASS' if ok else 'FAIL'}")
with open("results/tia_sim.txt", "w") as f:
    f.write(f"f-3dB = {results['f3db_MHz']:.1f} MHz\npeaking = "
            f"{results['peaking_dB']:.2f} dB\nstep swing = "
            f"{results['step_mV']:.1f} mV, settle(5%) = "
            f"{results['settle_ns']:.1f} ns\nintegrated output noise = "
            f"{results['noise_mV']:.3f} mV rms (link budget 0.569)\n")
    for name, p in checks:
        f.write(f"{'PASS' if p else 'FAIL'}  {name}\n")
    f.write(f"VERDICT: {'PASS' if ok else 'FAIL'}\n")
sys.exit(0 if ok else 1)
