#!/usr/bin/env python3
"""
run_hv_clamp.py — ngspice checks for the C30737-population HV fix
(docs/03): the fitted set-point network and the re-ratioed SHDN
divider. The 420 V design-point decks remain in sim/run_hv.py and
sim/hv_design.py; they now describe the S8664 stuffing variant.

Deck A — SET-POINT NETWORK (regulation): the real network
R31 7.68M / R32 75.0k / R33 140k with the DAC source swept
0..2.5 V. The LT3757 loop is a high-gain linear servo holding the
FB node at the 1.6 V reference (the deck is linear, so the DC
solution is exact up to the servo residual ~1.6/1e6 * (1+a+b)).
Checks the simulated V_HV at DAC zero-scale (the power-up demand
and hardware ceiling), mid-scale and full-scale against the
transfer equation V_HV = 253.21 - 54.857 * V_DAC.

Deck A2 — WORST-CORNER MAXIMUM DEMAND: same network at the stacked
worst-high corner (FBX reference at its datasheet max 1.631 V,
resistor ratios at +0.1% worst, FBX pin sinking its 100 nA max),
DAC at zero-scale. The simulated ceiling must agree with the
analytic corner (259.40 V) and stay <= 260 V.

Deck B — SHDN DIVIDER: node voltage vs VBUS for the old
(100k/33k) and new (143k/33k) dividers, plus the new divider with
a 1 uA leakage injected into the node (MCU pin allowance). The
new divider's node must stay below the LT3757's 1.17 V minimum
falling threshold at every VBUS; the old one is shown crossing it
(the defect being fixed).
"""
import os, subprocess, sys
import numpy as np

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

DECK_A = """* HV set-point network, C30737 fit (generated by sim/run_hv_clamp.py)
Vdac dac 0 0
Vref ref 0 1.6
Eservo hv 0 ref fb 1e6
R31 hv fb 7.68MEG
R32 fb 0 75.0k
R33 dac fb 140k
C34 fb 0 1n
.control
dc Vdac 0 2.5 0.25
wrdata results/hv_clamp_a.csv v(hv) v(fb)
quit
.endc
.end
"""

DECK_A2 = """* HV set-point worst corner (generated by sim/run_hv_clamp.py)
Vdac dac 0 0
Vref ref 0 1.631
Eservo hv 0 ref fb 1e6
R31 hv fb 7.68768MEG
R32 fb 0 74.925k
R33 dac fb 139.86k
Ifbx fb 0 100n
.control
op
wrdata results/hv_clamp_a2.csv v(hv)
quit
.endc
.end
"""

DECK_B = """* SHDN divider, {tag} (generated by sim/run_hv_clamp.py)
Vbus bus 0 5.0
R25 bus shdn {r25}
R26 shdn 0 33k
{extra}
.control
dc Vbus 4.75 5.25 0.25
wrdata results/hv_clamp_b{tag}.csv v(shdn)
quit
.endc
.end
"""


def run(deck, name):
    with open(f"sim/{name}.cir", "w") as f:
        f.write(deck)
    r = subprocess.run(["ngspice", "-b", f"sim/{name}.cir"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout[-2000:])
        raise SystemExit(f"ngspice failed: {name}")


def load2(path):
    """wrdata with one vector: columns (x, y); an `op` run writes a
    single (index, value) row instead of a sweep."""
    d = np.loadtxt(path)
    if d.ndim == 1:
        return None, d[-1]
    return d[:, 0], d[:, 1]


run(DECK_A, "hv_clamp_a")
d = np.loadtxt("results/hv_clamp_a.csv")
vdac, vhv = d[:, 0], d[:, 1]
at = {round(float(v), 2): float(h) for v, h in zip(vdac, vhv)}
sim_zero, sim_mid, sim_full = at[0.0], at[1.25], at[2.5]
print(f"SET-POINT (sim): V_DAC=0 -> {sim_zero:.2f} V (eq 253.21), "
      f"1.25 -> {sim_mid:.2f} V (eq 184.64), 2.5 -> {sim_full:.2f} V "
      f"(eq 116.07)")

run(DECK_A2, "hv_clamp_a2")
_, corner = load2("results/hv_clamp_a2.csv")
sim_corner = float(np.atleast_1d(corner)[0])
print(f"SET-POINT WORST CORNER (sim): max demand = {sim_corner:.2f} V "
      f"(analytic 259.40 V, bound 260 V)")

run(DECK_B.format(tag="old", r25="100k", extra=""), "hv_clamp_bold")
run(DECK_B.format(tag="new", r25="143k", extra=""), "hv_clamp_bnew")
run(DECK_B.format(tag="leak", r25="143k", extra="Ileak 0 shdn 1u"),
    "hv_clamp_bleak")
_, old_node = load2("results/hv_clamp_bold.csv")
_, new_node = load2("results/hv_clamp_bnew.csv")
_, leak_node = load2("results/hv_clamp_bleak.csv")
print(f"SHDN (sim): old divider node at VBUS=5.0 = {old_node[1]:.3f} V "
      f"(threshold min 1.17 -> converter enabled at power-up: defect)")
print(f"SHDN (sim): new divider node max over VBUS 4.75..5.25 = "
      f"{max(new_node):.3f} V; with 1 uA leakage = {max(leak_node):.3f} V "
      f"(must be < 1.17)")

checks = [
    ("zero-scale demand within 1 V of the transfer equation",
     abs(sim_zero - 253.21) < 1.0),
    ("mid-scale (V_DAC=1.25) within 1 V of the equation",
     abs(sim_mid - 184.64) < 1.0),
    ("full-scale demand within 1 V of the equation",
     abs(sim_full - 116.07) < 1.0),
    ("demand falls monotonically across the DAC span",
     bool(np.all(np.diff(vhv) < 0))),
    ("worst-corner max demand agrees with analytic 259.40 V (1 V)",
     abs(sim_corner - 259.40) < 1.0),
    ("worst-corner max demand <= 260 V (C30737 VBR max)",
     sim_corner <= 260.0),
    ("old SHDN divider enables at VBUS=5.0 (defect reproduced)",
     old_node[1] > 1.17),
    ("new SHDN divider node < 1.17 V at every VBUS corner",
     max(new_node) < 1.17),
    ("new SHDN node < 1.17 V with 1 uA leakage injected",
     max(leak_node) < 1.17),
]
print("\n--- checks ---")
ok = True
for name, p in checks:
    print(f"{'PASS' if p else 'FAIL'}  {name}")
    ok &= bool(p)
print(f"\nHV CLAMP NGSPICE VERDICT: {'PASS' if ok else 'FAIL'}")
with open("results/hv_sim_clamp.txt", "w") as f:
    f.write(f"set-point sim: zero={sim_zero:.2f} V, mid={sim_mid:.2f} V, "
            f"full={sim_full:.2f} V\n")
    f.write(f"worst-corner sim: max demand={sim_corner:.2f} V\n")
    f.write(f"shdn sim: old@5.0={old_node[1]:.3f} V, new max="
            f"{max(new_node):.3f} V, new+leak max={max(leak_node):.3f} V\n")
    for name, p in checks:
        f.write(f"{'PASS' if p else 'FAIL'}  {name}\n")
    f.write(f"VERDICT: {'PASS' if ok else 'FAIL'}\n")
sys.exit(0 if ok else 1)
